create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sender_name text not null check (char_length(sender_name) between 1 and 30),
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

drop policy if exists "authenticated users can read messages" on public.messages;
create policy "authenticated users can read messages"
on public.messages for select
to authenticated
using (true);

drop policy if exists "users can send their own messages" on public.messages;
create policy "users can send their own messages"
on public.messages for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "users can delete their own messages" on public.messages;
create policy "users can delete their own messages"
on public.messages for delete
to authenticated
using ((select auth.uid()) = user_id);

grant select, insert, delete on table public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;

create index if not exists messages_created_at_idx on public.messages(created_at);
create index if not exists messages_user_id_idx on public.messages(user_id);
